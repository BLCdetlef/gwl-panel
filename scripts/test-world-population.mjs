import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const read = async name => JSON.parse(await fs.readFile(new URL('../' + name, import.meta.url), 'utf8'));
const source = 'data/knowledge/world_population_global.json';
const [network, index, exported] = await Promise.all([read(source), read('data/knowledge/knowledge-index.json'), read('data/blc/blc-curve-export-v1.json')]);
const series = network.timeSeries[0];
assert.equal(series.dataNature, 'assessed_model_estimate');
assert.equal(series.reference.type, 'none');
assert.equal(series.points.length, 74);
assert.equal(series.points[0].year, 1950);
assert.equal(series.points[0].value, 2493092852 / 1e9);
assert.equal(series.points.at(-1).year, 2023);
assert.equal(series.points.at(-1).value, 8091734933 / 1e9);
const projection = network.projectionSeries[0];
assert.equal(projection.points.length, 77);
assert.equal(projection.points[0].year, 2024);
assert.equal(projection.points.at(-1).year, 2100);
assert.equal(projection.points.at(-1).value, 10180160744 / 1e9);
assert.equal(projection.observedSeriesId, series.id);
const all = [...series.historicalSeries.flatMap(h => h.points), ...series.points, ...projection.points];
assert.equal(all.length, new Set(all.map(p => p.year)).size, 'Abschnitte dürfen sich nicht zeitlich überlappen');
assert.equal(all[0].year, 1700);
assert.ok(series.historicalSeries[0].points.every(p => p.year < 1800));
assert.deepEqual(series.historicalSeries[1].points.map(p => p.year), Array.from({length: 150}, (_, i) => 1800 + i));
assert.deepEqual(network.healthContext.markerSignals, []);
assert.equal(index.systemBoundaries.flatMap(b => b.groups.flatMap(g => g.items)).filter(i => i.source === source).length, 1);
const curve = exported.curves.find(c => c.source === source);
assert.ok(curve);
assert.equal(curve.domainId, 'eah_tech_social_environment');
assert.equal(curve.curveRole, 'deep_dive');
assert.deepEqual(curve.observations.map(p => [p.year, p.value]), series.points.map(p => [p.year, p.value]));
assert.deepEqual(curve.historicalReconstruction.map(h => h.points.map(p => [p.year, p.value])), series.historicalSeries.map(h => h.points.map(p => [p.year, p.value])));
assert.deepEqual(curve.projections[0].points.map(p => [p.year, p.value]), projection.points.map(p => [p.year, p.value]));
assert.equal(curve.reference, undefined);
assert.equal(curve.displayDerivation.interpolation, false);
const csvLines = (await fs.readFile(new URL('../research/curve-candidates/world-population/population-with-projections.csv', import.meta.url), 'utf8')).split(/\r?\n/);
for (const segment of [{points: curve.observations, provenance: curve.observationProvenance}, ...curve.historicalReconstruction, ...curve.projections]) {
  const example = segment.provenance.valueExample;
  assert.ok(example);
  assert.equal(csvLines[example.sourceLine - 1], example.sourceRow);
  assert.equal(csvLines[0], example.sourceHeader);
  assert.equal(Number(example.sourceRow.split(',')[example.sourceColumnNumber - 1]), example.sourceValue);
  assert.equal(segment.points.find(p => p.year === example.year).value, example.sourceValue / example.divisor);
}
console.log('Weltbevölkerung geprüft: Originalwerte, Einheiten, Zeittrennung, Quellenwechsel, Index und Export ohne Grenzbewertung oder Organmarker.');
