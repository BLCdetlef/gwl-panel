import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const read=async p=>JSON.parse(await fs.readFile(new URL('../'+p,import.meta.url),'utf8'));
const source='data/knowledge/02_stoff_energiestroeme_aluminium_primaerproduktion_global.json';
const [candidate,network,index,exported]=await Promise.all([read('research/curve-candidates/02_stoff_energiestroeme_aluminium_primaerproduktion_global.json'),read(source),read('data/knowledge/knowledge-index.json'),read('data/blc/blc-curve-export-v1.json')]);
const main=network.timeSeries[0];
assert.equal(network.timeSeries.length,1);
assert.deepEqual(main.points.map(p=>p.year),Array.from({length:72},(_,i)=>1950+i));
assert.deepEqual(main.points.map(p=>[p.year,p.value]),candidate.observations.points.map(p=>[p.year,p.sourceValue/1e6]));
assert.equal(main.points[0].value,1.49);
assert.equal(main.points.at(-1).value,67.5);
assert.equal(main.dataNature,'assessed_model_estimate');
assert.equal(main.reference.type,'none');
assert.deepEqual(network.healthContext.systemImpacts,[]);
assert.equal(network.projectionSeries.length,1);
const future=network.projectionSeries[0];
assert.equal(future.scenario,'B2DS');
assert.equal(future.observedSeriesId,main.id);
assert.deepEqual(future.points.map(p=>[p.year,p.value]),[[2030,65.83549656925233],[2035,70.62168292171813],[2040,77.26412240615268],[2045,80.59892450562849],[2050,81.45976102686238]]);
assert.match(future.provenance.locator,/Q22/);
const entries=index.systemBoundaries.flatMap(b=>b.groups.flatMap(g=>g.items.filter(i=>i.source===source).map(i=>({b,g,i}))));
assert.equal(entries.length,1);assert.equal(entries[0].b.id,'eah_material_energy_flows');assert.equal(entries[0].b.label,'Stoff- und Energieströme');assert.equal(entries[0].g.label,'Rohstoffe');
const curves=exported.curves.filter(c=>c.source===source);assert.equal(curves.length,1);
const curve=curves[0];assert.equal(curve.curveRole,'deep_dive');assert.equal(curve.observations.length,72);assert.equal(curve.projections.length,1);assert.equal(curve.displayDerivation.interpolation,false);assert.equal(curve.chartGroup,undefined);
assert.deepEqual(curve.projections[0].points.map(p=>[p.year,p.value]),future.points.map(p=>[p.year,p.value]));
for(const point of curve.displayObservations)assert.ok(curve.observations.some(p=>p.year===point.year&&p.value===point.value));
console.log('PASS: eine Aluminiumkurve, 72 unveränderte USGS-Werte, 5 B2DS-Werte, Kategorien, keine Interpolation oder Organmarker.');
