import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
const root = new URL('../',import.meta.url);
const read = file => fs.readFileSync(new URL(file,root),'utf8');
const data=JSON.parse(read('data/knowledge/gwl_freshwater_blue_green_timeseries_v0.2.json'));
const series=data.timeSeries.find(s=>s.id==='blue_water_streamflow');
const example=series.provenance.valueExample;
const original=fs.readFileSync(new URL('research/freshwater/'+series.provenance.originalFile,root));
assert.equal(crypto.createHash('md5').update(original).digest('hex'),'2f4ebd7961fa88ca57e37e4c1ff27bb8');
const lines=original.toString('utf8').trimEnd().split(/\r?\n/);
assert.equal(lines[0],example.sourceHeader);
assert.equal(lines[example.sourceLine-1],example.sourceRow);
const fields=example.sourceRow.split(';').map(s=>s.replaceAll('"',''));
assert.deepEqual(fields.slice(0,5),['dis','global','2019','obsclim_histsoc_default','summed_deviations']);
assert.equal(Number(fields[example.sourceColumnNumber-1]),example.sourceValue);
const point=series.values.find(p=>p.year===example.year);
assert.equal(Number((example.sourceValue/example.divisor).toFixed(example.roundingDigits)),point.value);
assert.equal(Number((Number(fields[6])*100).toFixed(2)),point.iqrMin);
assert.equal(Number((Number(fields[7])*100).toFixed(2)),point.iqrMax);
const exported=JSON.parse(read('data/blc/blc-curve-export-v1.json')).curves.find(c=>c.seriesId===series.id);
assert.deepEqual(exported.observationProvenance.valueExample,example);
assert.equal(exported.displayObservations.find(p=>p.year===2019).value,point.value);
console.log('PASS: Blauwasser 2019, Original-CSV Zeile 120 / Spalte 6, Prozentumrechnung, IQR und Export geprüft.');
const historical=series.historicalSeries[0];
const historicalExample=historical.provenance.valueExample;
const historicalOriginal=fs.readFileSync(new URL('research/freshwater/porkka-2024-blue-water-original.csv',root));
assert.equal(crypto.createHash('md5').update(historicalOriginal).digest('hex'),'2b038a107dc3290ac12014a7b052c829');
const historicalLines=historicalOriginal.toString('utf8').trimEnd().split(/\r?\n/);
assert.equal(historicalLines[0],historicalExample.sourceHeader);
assert.equal(historicalLines[historicalExample.sourceLine-1],historicalExample.sourceRow);
const historicalFields=historicalExample.sourceRow.split(',').map(s=>s.replaceAll('"',''));
assert.deepEqual(historicalFields.slice(0,3),['global','1861','summed_deviations']);
assert.equal(Number(historicalFields[historicalExample.sourceColumnNumber-1]),historicalExample.sourceValue);
const historicalPoint=historical.values.find(p=>p.year===historicalExample.year);
assert.equal(Number((historicalExample.sourceValue/historicalExample.divisor).toFixed(historicalExample.roundingDigits)),historicalPoint.value);
assert.equal(Number((Number(historicalFields[4])*100).toFixed(2)),historicalPoint.iqrMin);
assert.equal(Number((Number(historicalFields[5])*100).toFixed(2)),historicalPoint.iqrMax);
assert.deepEqual(exported.historicalReconstruction[0].provenance.valueExample,historicalExample);
assert.equal(exported.displayHistoricalReconstruction[0].points.find(p=>p.year===1861).value,historicalPoint.value);
assert.ok(historical.provenance.sourceFile.endsWith('/global_land_area_with_local_deviations_annual_mean_ensemble_median_IQR.csv'));
console.log('PASS: Blauwasser-Rekonstruktion 1861, Original-CSV Zeile 172 / Spalte 4, Prozentumrechnung, IQR und Export geprüft.');
