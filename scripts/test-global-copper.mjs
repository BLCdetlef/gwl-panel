import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const read = async name => JSON.parse(await fs.readFile(new URL('../'+name,import.meta.url),'utf8'));
const source='data/knowledge/02_stoff_energiestroeme_kupfer_global.json';
const [candidate, network, index, exported] = await Promise.all([read('research/curve-candidates/02_stoff_energiestroeme_kupfer_global.json'),read(source),read('data/knowledge/knowledge-index.json'),read('data/blc/blc-curve-export-v1.json')]);
const entries=index.systemBoundaries.flatMap(boundary=>boundary.groups.flatMap(group=>group.items.filter(item=>item.source===source).map(item=>({boundary,item}))));
assert.equal(entries.length,1);
assert.equal(entries[0].boundary.id,'eah_material_energy_flows');
assert.equal(network.timeSeries.length,1);
const series=network.timeSeries[0];
assert.deepEqual(series.points.slice(0,64).map(p=>[p.year,p.value]),candidate.observations.points.map(p=>[p.year,p.sourceValue/1000]));
assert.equal(series.points.length,65);
assert.equal(series.points[0].value,4.738);
assert.equal(series.points[63].value,26.549);
assert.match(series.points[63].uncertainty,/Vorläufig/);
assert.equal(series.points[64].year,2024);
assert.equal(series.points[64].value,26.717);
assert.equal(series.points[64].kind,'historical_baseline');
assert.deepEqual(series.points[64].sourceRefs,['iea_gcm_outlook_2025']);
assert.deepEqual(network.projectionSeries[0].points.map(p=>[p.year,p.value]),[[2030,31.348],[2040,34.137],[2050,37.451]]);
assert.ok(network.projectionSeries[0].points.every(p=>p.year>2024));
assert.equal(series.methodBreaks[0].year,2024);
assert.match(series.methodNote,/historischer IEA-Basiswert/);
assert.equal(series.reference.type,'none');
assert.deepEqual(network.healthContext.systemImpacts,[]);
const curve=exported.curves.find(c=>c.source===source);
assert.ok(curve);
assert.equal(exported.curves.filter(c=>c.source===source).length,1);
assert.equal(curve.domainId,'eah_material_energy_flows');
assert.equal(curve.curveRole,'deep_dive');
assert.equal(curve.observations.length,65);
assert.equal(curve.projections.length,1);
assert.deepEqual(curve.projections[0].points.map(p=>p.year),[2030,2040,2050]);
assert.equal(curve.displayDerivation.interpolation,false);
assert.equal(curve.chartGroup,undefined);
assert.ok(curve.observationProvenance.locator.includes('S. 60'));
assert.ok(curve.projections[0].provenance.locator.includes('S. 293'));
for(const p of curve.displayObservations) assert.ok(curve.observations.some(original=>original.year===p.year && original.value===p.value));
console.log('Kupfer geprüft: eine Kurve, Quellenwerte und Einheiten, 2024 als historischer Basiswert, 3 STEPS-Stützwerte, Quellenwechsel und bestehende Darstellung.');
